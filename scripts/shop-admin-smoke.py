"""Current shop appearance and management flows; isolated TEST_BASE_URL required."""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
base=os.environ['TEST_BASE_URL']
results=Path('test-results');results.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'),args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':1000},reduced_motion='reduce')
    page=context.new_page();errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    login=context.request.post(base+'/api/auth',headers={'Origin':base},data={'login':os.environ['TEST_ADMIN_LOGIN'],'password':os.environ['TEST_ADMIN_PASSWORD']})
    assert login.status==200
    original=context.request.get(base+'/api/admin/appearance').json()
    original_content=context.request.get(base+'/api/admin/content').json()
    try:
        page.goto(base+'/main',wait_until='networkidle')
        expect(page.locator('.product-card')).to_have_count(4)
        expect(page.get_by_role('link',name='Поддержка',exact=True)).to_have_count(0)
        expect(page.get_by_role('heading',name='Свежие покупки')).to_be_visible()
        page.get_by_role('combobox',name='Сортировка').click()
        page.get_by_role('option',name='Сначала дороже',exact=True).click()
        expect(page.locator('.product-card').first).to_contain_text('OVERLORD')
        page.get_by_role('combobox',name='Сортировка').focus()
        page.keyboard.press('ArrowDown');page.keyboard.press('Home');page.keyboard.press('Enter')
        page.goto(base+'/admin',wait_until='networkidle')
        nav=page.get_by_role('navigation',name='Разделы админки')
        nav.get_by_role('button',name='Оформление',exact=True).click()
        page.get_by_label('Загрузить: Аватарка сервера',exact=True).set_input_files('public/images/minecraft/diamond.png')
        expect(page.get_by_label('Ссылка: Аватарка сервера',exact=True)).to_have_value(__import__('re').compile(r'^/api/media/'))
        page.get_by_label('Заголовок баннера',exact=True).fill('Баннер из админки')
        page.get_by_role('button',name='Сохранить изменения').click()
        expect(page.get_by_role('status')).to_contain_text('Сохранено')
        visitor=browser.new_page()
        visitor.goto(base+'/main',wait_until='networkidle')
        expect(visitor.get_by_role('heading',name='Баннер из админки',exact=True)).to_be_visible()
        expect(visitor.locator('.brand-mark img').first).to_be_visible()
        nav.get_by_role('button',name='Аналитика',exact=True).click()
        expect(page.get_by_role('heading',name='Выручка по дням')).to_be_visible()
        page.get_by_role('combobox',name='Период аналитики').click()
        page.get_by_role('option',name='7 дней',exact=True).click()
        expect(page.locator('.chart-column')).to_have_count(7)
        page.screenshot(path=str(results/'analytics.png'),full_page=True)
        nav.get_by_role('button',name='Политики',exact=True).click()
        expect(page.get_by_role('heading',name='Политики и сведения о владельце')).to_be_visible()
        for path in ['/privacy','/terms']:
            visitor.goto(base+path,wait_until='networkidle')
            expect(visitor.locator('.legal-document')).to_be_visible()
        nav.get_by_role('button',name='Акции',exact=True).click()
        page.get_by_role('button',name='Добавить акцию',exact=True).click()
        page.get_by_label('Название',exact=True).fill('Browser sale')
        page.get_by_label('Скидка, %',exact=True).fill('25')
        page.get_by_role('button',name='Сохранить акцию',exact=True).click()
        expect(page.get_by_role('heading',name='Browser sale')).to_be_visible()
        visitor.goto(base+'/main',wait_until='networkidle')
        expect(visitor.locator('.store-offers')).to_contain_text('Browser sale')
        page.locator('.campaign-list article').filter(has_text='Browser sale').get_by_role('button',name='Удалить',exact=True).click()
        page.get_by_role('button',name='Удалить акцию',exact=True).click()
        expect(page.get_by_role('heading',name='Browser sale')).to_have_count(0)
        nav.get_by_role('button',name='Тексты и секции',exact=True).click()
        page.get_by_label('Заголовок магазина',exact=True).fill('<img src=x onerror=window.xss=true>')
        page.get_by_label('Показывать секцию «Новости»',exact=True).uncheck()
        page.get_by_role('button',name='Сохранить содержимое',exact=True).click()
        expect(page.get_by_role('status')).to_contain_text('сохранены')
        visitor.goto(base+'/main',wait_until='networkidle')
        expect(visitor.get_by_role('heading',name='<img src=x onerror=window.xss=true>',exact=True)).to_be_visible()
        expect(visitor.locator('.home-news')).to_have_count(0)
        assert visitor.evaluate('window.xss === undefined')
        nav.get_by_role('button',name='Товары',exact=True).click()
        page.locator('.admin-table tbody tr').first.get_by_role('button',name='Копировать',exact=True).click()
        page.get_by_role('button',name='Сохранить товар',exact=True).click()
        copied=page.locator('.admin-table tbody tr').filter(has_text='(копия)')
        expect(copied).to_have_count(1)
        expect(copied).to_contain_text('Скрыт')
        copied.get_by_role('checkbox').check()
        page.get_by_role('button',name='Показать выбранные',exact=True).click()
        expect(copied).to_contain_text('На сайте')
        copied.get_by_role('checkbox').check()
        page.get_by_role('button',name='Скрыть выбранные',exact=True).click()
        expect(copied).to_contain_text('Скрыт')
        nav.get_by_role('button',name='Заказы',exact=True).click()
        with page.expect_download() as download_info:
            page.get_by_role('link',name='Скачать CSV').click()
        assert download_info.value.suggested_filename.endswith('.csv')
        assert not errors,errors
        print('PASS: custom sorting with keyboard, removed support, recent purchases, logo upload, banner persistence, analytics periods, legal pages, campaigns, editable sections/XSS escaping, product duplication/bulk visibility and CSV download')
    finally:
        restored=context.request.put(base+'/api/admin/appearance',headers={'Origin':base},data=original)
        assert restored.status==200
        assert context.request.put(base+'/api/admin/content',headers={'Origin':base},data=original_content).status==200
        browser.close()
