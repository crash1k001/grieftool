"""Run against an isolated running app. Requires playwright + Chromium.
TEST_BASE_URL and TEST_ADMIN_PASSWORD must be provided in the environment.
"""
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base = os.environ.get('TEST_BASE_URL', 'http://localhost:3000')
password = os.environ['TEST_ADMIN_PASSWORD']
results = Path('test-results')
results.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True, executable_path=os.environ.get('CHROMIUM_PATH', '/usr/bin/chromium'), args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 1050})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(base + '/main', wait_until='networkidle')
    expect(page.get_by_role('button', name='Купить')).to_have_count(4)
    page.screenshot(path=str(results / 'store-desktop.png'), full_page=True)
    page.get_by_role('navigation', name='Категории товаров').get_by_role('button', name='Ключи').click()
    expect(page.get_by_role('button', name='Купить')).to_have_count(1)
    page.get_by_role('navigation', name='Категории товаров').get_by_role('button', name='Привилегии').click()
    page.get_by_role('textbox', name='Поиск товаров', exact=True).fill('LEGEND')
    expect(page.get_by_role('button', name='Купить')).to_have_count(1)
    page.get_by_role('textbox', name='Поиск товаров', exact=True).fill('')
    page.get_by_role('button', name='Купить').first.click()
    dialog = page.get_by_role('dialog')
    expect(dialog).to_be_visible()
    dialog.get_by_role('textbox', name='Твой игровой ник').fill('Browser_Player')
    dialog.get_by_role('checkbox').check()
    dialog.get_by_role('button', name='Сохранить заказ').click()
    expect(dialog.get_by_role('heading', name='Заявка на покупку создана')).to_be_visible()
    expect(dialog).to_contain_text('Деньги не списаны')
    dialog.get_by_role('button', name='Понятно').click()
    page.locator('details').first.locator('summary').click()
    expect(page.locator('details').first).to_have_attribute('open', '')
    page.goto(base + '/admin', wait_until='networkidle')
    page.get_by_label('Логин', exact=True).fill(os.environ.get('TEST_ADMIN_LOGIN', 'crashovh'))
    page.get_by_label('Пароль администратора', exact=True).fill(password)
    page.get_by_role('button', name='Войти в панель').click()
    expect(page.get_by_role('heading', name='Обзор', exact=True)).to_be_visible()
    page.get_by_role('navigation', name='Разделы админки').get_by_role('button', name='Товары', exact=True).click()
    page.get_by_role('button', name='Добавить товар').click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_label('Название', exact=True).fill('BROWSER_TEST')
    dialog.get_by_label('Описание и состав', exact=True).fill('Проверка сохранения товара из браузера')
    dialog.get_by_label('Цена, ₽', exact=True).fill('123')
    dialog.get_by_label('Скидка, %', exact=True).fill('20')
    dialog.get_by_role('button', name='Сохранить товар').click()
    expect(page.locator('.table-product').filter(has_text='BROWSER_TEST')).to_be_visible()
    page.screenshot(path=str(results / 'admin-desktop.png'), full_page=True)
    row = page.get_by_role('row').filter(has_text='BROWSER_TEST')
    row.get_by_role('button', name='Изменить', exact=True).click()
    dialog = page.get_by_role('dialog')
    dialog.get_by_label('Цена, ₽', exact=True).fill('150')
    dialog.get_by_role('button', name='Сохранить товар').click()
    expect(page.get_by_role('row').filter(has_text='BROWSER_TEST')).to_contain_text('150')
    page.get_by_role('row').filter(has_text='BROWSER_TEST').get_by_role('button', name='Удалить BROWSER_TEST').click()
    page.get_by_role('dialog').get_by_role('button', name='Удалить', exact=True).click()
    expect(page.locator('.table-product').filter(has_text='BROWSER_TEST')).to_have_count(0)
    page.get_by_role('navigation', name='Разделы админки').get_by_role('button', name='Настройки сайта', exact=True).click()
    page.get_by_label('Метка на главном баннере', exact=True).fill('НОВЫЙ УРОВЕНЬ ТВОЕЙ ИГРЫ')
    page.get_by_role('button', name='Сохранить настройки').click()
    expect(page.get_by_role('status')).to_contain_text('Настройки опубликованы')
    page.get_by_role('button', name='Выйти', exact=True).click()
    expect(page.get_by_role('button', name='Войти в панель')).to_be_visible()
    for width in [390, 360]:
        page.set_viewport_size({'width': width, 'height': 844})
        page.goto(base + '/main', wait_until='networkidle')
        expect(page.get_by_role('button', name='Купить')).to_have_count(4)
        assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Horizontal page overflow'
        page.screenshot(path=str(results / f'store-mobile-{width}.png'), full_page=True)
    assert not errors, errors
    browser.close()
    print('PASS: catalog, filters, checkout, FAQ, admin login, product CRUD, settings, logout, 390/360px mobile; no page errors')
